void DCT_2D(uint8_t** pre, int16_t** post ) {
    double tableau_prod_1[N][N] = {0};

 
    // Produit matriciel C * pre
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < N; j++) {
            for (int k = 0; k < N; k++) {
                tableau_prod_1[i][j] += tableau_cos_C[i][k] * (pre[k][j]-128);
            }
        }
    }

    // Produit matriciel C * pre * Ct
    for (int i = 0; i < N; i++) {
        
        for (int j = 0; j < N; j++) {
            double somme=0.0;
            for (int k = 0; k < N; k++) {
                somme += tableau_prod_1[i][k] * tableau_cos_Ct[k][j];
            }
            post[i][j] = (int16_t)round(somme);
   
        }
    }
}

